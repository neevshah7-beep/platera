import { chromium } from 'playwright-core'
const browser = await chromium.launch({ executablePath: 'C:/Program Files/Google/Chrome/Application/chrome.exe', args: ['--enable-gpu', '--use-angle=d3d11', '--ignore-gpu-blocklist'] })
const page = await (await browser.newContext({ viewport: { width: 1536, height: 864 }, deviceScaleFactor: 1.25 })).newPage()
const errors = []
page.on('pageerror', (e) => errors.push(e.message))
await page.goto('http://localhost:3000/piece/five-petal-necklace-set', { waitUntil: 'load', timeout: 180000 })
await page.waitForTimeout(2500)
await page.locator('#originals').scrollIntoViewIfNeeded()
await page.waitForTimeout(1200)
await page.screenshot({ path: 'look/orig-0-gallery.png' })
await page.locator('#originals button').first().click()
await page.waitForTimeout(1200)
await page.screenshot({ path: 'look/orig-1-viewer.png' })
await page.mouse.click(768, 430)
await page.waitForTimeout(900)
await page.mouse.move(820, 470, { steps: 5 })
await page.waitForTimeout(600)
await page.screenshot({ path: 'look/orig-2-zoom.png' })
await page.keyboard.press('Escape')
// Case room
await page.goto('http://localhost:3000/necklaces', { waitUntil: 'load' })
await page.waitForTimeout(6000)
const btn = page.locator('.collection-originals').first()
await btn.waitFor({ timeout: 20000 })
await page.screenshot({ path: 'look/orig-3-case.png' })
await btn.click()
await page.waitForTimeout(1200)
await page.screenshot({ path: 'look/orig-4-case-viewer.png' })
console.log('errors', errors)
await browser.close()

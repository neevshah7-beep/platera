import { chromium } from 'playwright-core'
const base = 'http://localhost:3001'
const browser = await chromium.launch({ executablePath: 'C:/Program Files/Google/Chrome/Application/chrome.exe' })
const page = await (await browser.newContext({ viewport: { width: 1440, height: 900 } })).newPage()
page.on('console', (m) => m.type() === 'error' && console.log('console', m.text().slice(0, 300)))
page.on('response', (r) => r.status() >= 400 && console.log('http', r.status(), r.url().slice(0, 120)))
await page.goto(`${base}/piece/fringe-line-necklace`)
await page.getByRole('button', { name: 'Add to bag' }).first().click()
await page.getByText('Added to your bag.').waitFor()
await page.goto(`${base}/checkout`)
console.log(await page.locator('h1').innerText(), page.url())
await page.getByLabel('Full name').fill('Test Buyer')
await page.getByLabel('Mobile number').fill('9876543210')
await page.getByLabel('Email, for your receipt').fill('buyer@example.test')
await page.getByLabel('House, building, street').fill('12 Test Road')
await page.getByLabel('City').fill('Mumbai')
await page.getByLabel('PIN code').fill('400091')
await page.getByLabel(/I’ve read these conditions/).check()
await page.getByRole('button', { name: /^Pay/ }).click()
await page.waitForTimeout(8000)
console.log(page.url())
console.log((await page.locator('[role=alert], .text-ruby-bright, [aria-live]').allInnerTexts()).join(' | ').slice(0, 500))
await page.screenshot({ path: 'look/e2e/dbg-checkout.png', fullPage: true })
await browser.close()

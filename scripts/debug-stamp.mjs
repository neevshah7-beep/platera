import { chromium } from 'playwright-core'
const browser = await chromium.launch({ executablePath: 'C:/Program Files/Google/Chrome/Application/chrome.exe', args: ['--enable-gpu', '--use-angle=d3d11'] })
const page = await (await browser.newContext({ viewport: { width: 1440, height: 900 } })).newPage()
await page.goto('http://localhost:3000/', { waitUntil: 'load', timeout: 180_000 })
await page.waitForSelector('.entry-enter[data-ready="true"]', { timeout: 120_000 })
await page.click('.entry-enter')
await page.waitForTimeout(1500)
const y = await page.evaluate(() => document.querySelector('#stamp-title').closest('section').getBoundingClientRect().top + scrollY)
await page.evaluate((v) => window.scrollTo(0, v), Math.round(y + 50))
await page.waitForTimeout(3000)
const b = await page.locator('.stamp-hold').boundingBox()
console.log('box', b)
console.log('at point', await page.evaluate(([x, y]) => { const e = document.elementFromPoint(x, y); return e?.className + ' / ' + e?.tagName }, [b.x + b.width / 2, b.y + b.height / 2]))
await page.mouse.move(b.x + b.width / 2, b.y + b.height / 2)
await page.mouse.down()
await page.waitForTimeout(600)
console.log('phase', await page.locator('.stamp-hold').getAttribute('data-phase'))
await page.mouse.up()
await browser.close()

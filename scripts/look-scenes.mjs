// Visual check of Scenes 3 and 4 (desktop): hold-and-strike, then the collection with a hover.
import { chromium } from 'playwright-core'
import { mkdirSync } from 'node:fs'
mkdirSync('look', { recursive: true })
const browser = await chromium.launch({ executablePath: 'C:/Program Files/Google/Chrome/Application/chrome.exe', args: ['--enable-gpu', '--use-angle=d3d11', '--ignore-gpu-blocklist', '--enable-webgl'] })
const page = await (await browser.newContext({ viewport: { width: 1440, height: 900 } })).newPage()
const errors = []
page.on('pageerror', (e) => errors.push(e.message))
page.on('console', (m) => m.type() === 'error' && errors.push(m.text().slice(0, 300)))
await page.goto('http://localhost:3000/', { waitUntil: 'load', timeout: 180_000 })
await page.waitForSelector('.entry-enter[data-ready="true"]', { timeout: 120_000 })
await page.click('.entry-enter')
await page.waitForTimeout(1500)
const topOf = (sel) => page.evaluate((s) => document.querySelector(s).getBoundingClientRect().top + scrollY, sel)
const stamp = await topOf('#stamp-title')
const stampSection = await page.evaluate(() => document.querySelector('#stamp-title').closest('section').getBoundingClientRect().top + scrollY)
await page.evaluate((y) => window.scrollTo(0, y), Math.round(stampSection + 50))
await page.waitForTimeout(3500)
await page.screenshot({ path: 'look/stamp-0-idle.png' })
const btn = await page.locator('.stamp-hold').boundingBox()
await page.mouse.move(btn.x + btn.width / 2, btn.y + btn.height / 2)
await page.mouse.down()
await page.waitForTimeout(900)
console.log('phase after hold', await page.locator('.stamp-hold').getAttribute('data-phase'), 'el', await page.evaluate(([x,y])=>document.elementFromPoint(x,y)?.className, [btn.x+btn.width/2, btn.y+btn.height/2]))
await page.screenshot({ path: 'look/stamp-1-holding.png' })
await page.waitForTimeout(900)
await page.mouse.up()
console.log('phase after release', await page.locator('.stamp-hold').getAttribute('data-phase'))
await page.waitForTimeout(220)
await page.screenshot({ path: 'look/stamp-2-strike.png' })
await page.waitForTimeout(250)
await page.screenshot({ path: 'look/stamp-3-sparks.png' })
await page.waitForTimeout(1500)
await page.screenshot({ path: 'look/stamp-4-struck.png' })
const col = await page.evaluate(() => document.querySelector('#collection-title').closest('section').getBoundingClientRect().top + scrollY)
await page.evaluate((y) => window.scrollTo(0, y), Math.round(col + 900 * 1.2))
await page.waitForTimeout(4000)
await page.screenshot({ path: 'look/collection-0.png' })
await page.mouse.move(760, 520)
await page.waitForTimeout(1200)
await page.screenshot({ path: 'look/collection-1-hover.png' })
void stamp
console.log('errors', errors.slice(0, 5))
await browser.close()
